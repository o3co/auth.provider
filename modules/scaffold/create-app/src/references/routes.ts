/** The route reference: every route the full template with every opt-in serves, as one document. */
import { join } from "node:path";
import { assembledIn, type RouteSeen } from "./assembled.ts";

/** Every route full with every opt-in serves, by path, then method. */
export async function routesIn(root: string): Promise<RouteSeen[]> {
	return [...(await assembledIn(root)).routes].sort((a, b) =>
		a.path === b.path ? (a.method < b.method ? -1 : 1) : a.path < b.path ? -1 : 1,
	);
}

/** The reference, generated: one table of every route. */
export function routesOf(routes: readonly RouteSeen[]): string {
	const lines = routes.map(
		(r) =>
			`| ${r.method} | \`${r.path}\` | \`${r.owner}\` | ${(r.takes ?? ["form"]).join(", ")} | ${r.policies.map((p) => `\`${p}\``).join(", ")} | ${r.cors ? "yes" : ""} |`,
	);
	return `${[
		"# Routes",
		"",
		"Generated by `create-app` from the routes the full template with every opt-in serves on the trial's settings: do not edit; run `pnpm --filter @mod/create-app run configuration`.",
		"What a route answers is in the card of the package it is from; a path ending in `*` takes every path under it, and the paths within are in that card.",
		"Body is what a route takes, a form where it names none; its policies apply in this order before it; CORS says whether it takes cross-origin requests.",
		"",
		"| Method | Path | From | Body | Policies | CORS |",
		"|---|---|---|---|---|---|",
		...lines,
	].join("\n")}\n`;
}

/** Where the reference lies in the workspace. */
export const routesFile = (root: string) => join(root, "docs", "routes.md");
