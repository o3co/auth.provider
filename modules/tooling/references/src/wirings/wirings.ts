/** The wiring reference: for each module whose store a wiring ties to an implementation, the wirings to compose. */
import { join } from "node:path";
import type { Pkg } from "@mod/guard-imports";

/** One module's row: the name a boot refusal gives it, its package, and each package that wires it. */
export interface Row {
	/** The package's name without its scope, the name the module is refused by. */
	readonly module: string;
	readonly owner: string;
	readonly wirings: readonly string[];
}

const unscoped = (name: string) => name.replace(/^@[^/]+\//, "");

/** Each package that a wiring's `wires` names, with every wiring naming it, by the module's name. */
export function wiringsIn(packages: readonly Pkg[]): Row[] {
	const wirings = packages.filter(
		(p) => p.manifest.kind === "wiring" && typeof p.manifest.wires === "string",
	);
	return [...Map.groupBy(wirings, (w) => w.manifest.wires as string)]
		.map(([owner, ws]) => ({
			module: unscoped(owner),
			owner,
			wirings: ws.map((w) => w.name).toSorted(),
		}))
		.toSorted((a, b) => a.module.localeCompare(b.module));
}

/** The file the reference is written to. */
export const wiringsFile = (root: string) => join(root, "docs", "wirings.md");

// Packages are named, never linked: a document points at no file in another directory (the guard's G12).
export function wiringsOf(rows: readonly Row[]): string {
	return [
		"# The wiring a module's store needs",
		"",
		"Generated by `references` from each wiring's manifest (`wires`): do not edit; run `pnpm --filter @mod/references run configuration`.",
		"",
		"A module that keeps records takes its store through a wiring, which ties the module's store interfaces to an implementation. Where no wiring is composed, the app's boot refuses, naming the module and the contract it lacks: `refused <module>: no module provides <contract>`. Find the module the refusal names below and compose the wiring beside it; the wiring's card says what it keeps. Several modules may be refused for one missing store, where others take the same contract: compose the wiring for the one this table lists.",
		"",
		"| Module refused | Wiring to compose |",
		"|---|---|",
		...rows.map((r) => `| \`${r.module}\` | ${r.wirings.map((w) => `\`${w}\``).join(", ")} |`),
		"",
	].join("\n");
}
