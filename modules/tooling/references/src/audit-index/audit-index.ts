/** The audit index's generated parts: the cards, and what each package depends on. */
import { readFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { readWorkspace } from "@mod/guard-imports";

/** An internal module, by its card. */
export interface Internal {
	readonly name: string;
	/** Relative to the workspace root. */
	readonly dir: string;
	readonly line: string | undefined;
}

/** A workspace package as the index reads it. */
export interface Entry {
	readonly name: string;
	/** Relative to the workspace root. */
	readonly dir: string;
	readonly kind: string | undefined;
	readonly line: string | undefined;
	readonly internal: readonly Internal[];
	/** The workspace packages its manifest names to run with, sorted. */
	readonly dependsOn: readonly string[];
}

const generated =
	"Generated by `references` from each workspace package's card and manifest: do not edit; run `pnpm --filter @mod/references run configuration`.";

/** The line a card opens with: its first paragraph (an internal module's without its prefix), or else its first responsibility. */
export function cardLine(card: string): string | undefined {
	const [, ...rest] = card.split(/\n\s*\n/);
	const first = rest[0]?.trim();
	if (first !== undefined && !first.startsWith("#")) {
		return first.replace(/\s*\n\s*/g, " ").replace(/^Internal module of `[^`]+`: /, "");
	}
	const listed = card.match(/^## Responsibilities\n- (.+)$/m);
	return listed?.[1];
}

/** Every workspace package but the root, by its directory, with its internal modules. */
export function auditIndexIn(root: string): Entry[] {
	const packages = readWorkspace(root);
	const names = new Set(packages.map((p) => p.name));
	return packages
		.map((p) => {
			const internal = p.files
				.filter((f) => /^src\/.+\/README\.md$/.test(f) && !f.includes("/test/"))
				.map((f) => ({
					name: dirname(f).split("/").at(-1) ?? "",
					dir: relative(root, join(p.dir, dirname(f))),
					line: cardLine(readFileSync(join(p.dir, f), "utf8")),
				}))
				.sort((a, b) => a.dir.localeCompare(b.dir));
			const { dependencies = {}, peerDependencies = {} } = p.manifest;
			const dependsOn = [...Object.keys(dependencies), ...Object.keys(peerDependencies)]
				.filter((d) => names.has(d))
				.sort();
			return {
				name: p.name,
				dir: relative(root, p.dir),
				kind: p.manifest.kind,
				line: p.card === undefined ? undefined : cardLine(p.card),
				internal,
				dependsOn: [...new Set(dependsOn)],
			};
		})
		.filter((e) => e.dir !== "")
		.sort((a, b) => a.dir.localeCompare(b.dir));
}

/** The directory under `modules` a package lies in. */
const groupOf = (e: Entry) => e.dir.split("/")[1] ?? e.dir;

const grouped = (entries: readonly Entry[]) =>
	[...Map.groupBy(entries, groupOf)].sort(([a], [b]) => a.localeCompare(b));

const said = (line: string | undefined) => line ?? "its card names no line.";

// Directories are named, never linked: a document points at no file in another directory (the guard's G12).
export function cardsOf(entries: readonly Entry[]): string {
	const sections = grouped(entries).map(([group, members]) => {
		const lines = members.flatMap((e) => [
			`- \`${e.name}\` (${e.kind ?? "no kind"}, \`${e.dir}\`): ${said(e.line)}`,
			...e.internal.map(
				(i) => `  - \`${i.name}\` (\`${relative(e.dir, i.dir)}\`): ${said(i.line)}`,
			),
		]);
		return `## ${group}\n\n${lines.join("\n")}\n`;
	});
	const head = [
		"# Module cards",
		"",
		generated,
		"Each workspace package, by the directory under `modules` it lies in, with its kind, its directory and the line its card opens with; its internal modules beneath it, each by its directory within the package. A card is the `README.md` of the directory named.",
		"",
	];
	return [...head, ...sections].join("\n");
}

export function dependenciesOf(entries: readonly Entry[]): string {
	const groups = grouped(entries);
	const id = new Map(groups.map(([group], i) => [group, `d${i}`]));
	const groupByName = new Map(entries.map((e) => [e.name, groupOf(e)]));
	const edges = new Set(
		entries.flatMap((e) =>
			e.dependsOn
				.map((d) => groupByName.get(d))
				.filter((g) => g !== undefined && g !== groupOf(e))
				.map((g) => `  ${id.get(groupOf(e))} --> ${id.get(g as string)}`),
		),
	);
	const graph = [
		"```mermaid",
		"flowchart LR",
		...groups.map(([group]) => `  ${id.get(group)}["${group}"]`),
		...[...edges].sort(),
		"```",
		"",
	];
	const tables = groups.map(([group, members]) => {
		const rows = members.map((e) => {
			const on = e.dependsOn.length === 0 ? "none" : e.dependsOn.map((d) => `\`${d}\``).join(", ");
			return `| \`${e.name}\` | ${e.kind ?? "no kind"} | ${on} |`;
		});
		return [
			`### ${group}`,
			"",
			"| Package | Kind | Depends on |",
			"|---|---|---|",
			...rows,
			"",
		].join("\n");
	});
	const head = [
		"# Dependencies",
		"",
		generated,
		"What each workspace package depends on to run: the workspace packages its manifest names in `dependencies` and `peerDependencies`, tests' left out. The guard holds shipped imports to the manifest (G8, G34) and the direction to the kinds' order (G10); a package's card says what it takes from each.",
		"",
		"## Between directories",
		"",
		"An arrow from a directory under `modules` to another: a package in the first depends on one in the second.",
		"",
	];
	return [...head, ...graph, "## By package", "", ...tables].join("\n");
}

export const cardsFile = (root: string) => join(root, "docs", "audit", "cards.md");
export const dependenciesFile = (root: string) => join(root, "docs", "audit", "dependencies.md");
