/** The route reference: every route the full template with every opt-in serves, as one document. */
import { join } from "node:path";
import { assembledIn, type Kept, type RouteSeen } from "./assembled.ts";

/** Every route full with every opt-in serves, by path, then method. */
export async function routesIn(root: string): Promise<RouteSeen[]> {
	return [...(await assembledIn(root)).routes].sort((a, b) =>
		a.path === b.path ? (a.method < b.method ? -1 : 1) : a.path < b.path ? -1 : 1,
	);
}

const changes = (r: RouteSeen) =>
	r.changesState === undefined ? "" : r.changesState ? "yes" : "no";
const keptBy = (kept: Kept | undefined) =>
	kept === undefined
		? ""
		: "policy" in kept
			? `\`${kept.policy}\``
			: kept.reason.replaceAll("|", "\\|");

/** The reference, generated: one table of every route. */
export function routesOf(routes: readonly RouteSeen[]): string {
	const lines = routes.map(
		(r) =>
			`| ${r.method} | \`${r.path}\` | \`${r.owner}\` | ${(r.takes ?? ["form"]).join(", ")} | ${r.policies.map((p) => `\`${p}\``).join(", ")} | ${changes(r)} | ${keptBy(r.ownSite)} | ${keptBy(r.perSource)} | ${r.cors ? "yes" : ""} |`,
	);
	return `${[
		"# Routes",
		"",
		"Generated by `references` from the routes the full template with every opt-in serves on the trial's settings: do not edit; run `pnpm --filter @mod/references run configuration`.",
		"What a route answers is in the card of the package it is from; a `*` within a path takes one segment, a path ending in `*` every path under it, and the paths within are in that card; which declaration comes first for a path is in `http`'s card.",
		"Body is what a route takes, a form where it names none; its policies apply in this order before it; CORS says whether it takes cross-origin requests.",
		"Changes state is yes for any method but GET, and for a GET as it declares; Other sites and Per source name the route's policy marked `own-site` or `per-source` for its method, or else its declared reason, and `http` checks them at boot for a route that declares them.",
		"Marks and reasons say where a guarantee is kept and where it is not: a mark is its owner's own claim, and a declaration proves nothing.",
		"",
		"| Method | Path | From | Body | Policies | Changes state | Other sites | Per source | CORS |",
		"|---|---|---|---|---|---|---|---|---|",
		...lines,
	].join("\n")}\n`;
}

/** Where the reference lies in the workspace. */
export const routesFile = (root: string) => join(root, "docs", "routes.md");
