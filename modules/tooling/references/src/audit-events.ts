/** The audit event reference: every module's declared events, as one document. */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { workspacePackages } from "./workspace.ts";

/** One declared event, as `audit`'s `auditEvents` takes it. */
export interface Declared {
	readonly attributes: readonly string[];
	readonly when: string;
}

/** Each package exporting `./audit-events`, with its declarations, by package name. */
export async function declarationsIn(
	root: string,
): Promise<{ readonly owner: string; readonly events: Readonly<Record<string, Declared>> }[]> {
	const found = [];
	for (const [name, dir] of workspacePackages(root)) {
		if (dir === root) continue;
		const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
		const entry: string | undefined = manifest.exports?.["./audit-events"];
		if (!entry) continue;
		const events = (await import(join(dir, entry))).default as Record<string, Declared>;
		found.push({ owner: name, events });
	}
	return found.sort((a, b) => (a.owner < b.owner ? -1 : 1));
}

/** Each kind more than one module declares, unlike in some way: one kind holds one meaning. */
export function unlikeKinds(
	modules: readonly {
		readonly owner: string;
		readonly events: Readonly<Record<string, Declared>>;
	}[],
): string[] {
	const first = new Map<string, { owner: string; declared: string }>();
	const unlike = new Set<string>();
	for (const { owner, events } of modules) {
		for (const [kind, declared] of Object.entries(events)) {
			const shape = JSON.stringify({
				attributes: [...declared.attributes].sort(),
				when: declared.when,
			});
			const held = first.get(kind);
			if (!held) first.set(kind, { owner, declared: shape });
			else if (held.declared !== shape)
				unlike.add(`${kind}: ${held.owner} and ${owner} declare it differently`);
		}
	}
	return [...unlike];
}

const text = (value: string) => value.replaceAll("|", "\\|").replaceAll("\n", " ");

/** The reference, generated: one table per module, its kinds in code point order. */
export function auditReferenceOf(
	modules: readonly {
		readonly owner: string;
		readonly events: Readonly<Record<string, Declared>>;
	}[],
): string {
	const blocks = modules.map(({ owner, events }) =>
		[
			`## ${owner}`,
			"",
			"| Kind | Attributes | Recorded when |",
			"|---|---|---|",
			...Object.keys(events)
				.sort()
				.map((kind) => {
					const e = events[kind] as Declared;
					const attributes = e.attributes.map((a) => `\`${a}\``).join(", ");
					return `| \`${kind}\` | ${attributes} | ${text(e.when)} |`;
				}),
		].join("\n"),
	);
	return `${[
		"# Audit events",
		"",
		"Generated by `create-app` from each module's `./audit-events` declarations: do not edit; run `pnpm --filter @mod/create-app run configuration`.",
		"Every event carries its kind and the time `kernel`'s clock gives it, and a subject where the table's module names one.",
		"`audit` bounds a `userAgent`, the request's own text, before any receiver gets it: a `?` for each character outside RFC 6749's NQSCHAR, at most 200 characters; the subject and other attributes stay as written.",
		"",
		...blocks.flatMap((b) => [b, ""]),
	]
		.join("\n")
		.trimEnd()}\n`;
}

/** Where the reference lies in the workspace. */
export const auditReferenceFile = (root: string) => join(root, "docs", "audit-events.md");
