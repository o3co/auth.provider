import { type Item, roles, type Spec } from "./checklist.ts";
import { classOf } from "./ids.ts";

/** A test that names an item: its package, its file in the package, and its title. */
export interface TestRef {
	readonly pkg: string;
	readonly file: string;
	readonly title: string;
	/** Where it is written: its suites' titles, outermost first, then its own (`null` for one not a plain string). */
	readonly path: readonly (string | null)[];
	/** Whether it is a suite's title, met by the tests inside it. */
	readonly suite: boolean;
	/** The faults its title marks; none where it marks none. */
	readonly faults?: readonly string[];
}

/** The faults a guarantee names that no test naming it marks. */
export const unmarkedFaults = (item: Item, refs: readonly TestRef[]) =>
	(item.faults ?? []).filter((f) => !refs.some((r) => r.faults?.includes(f)));

export type StaticStatus = "mapped" | "hole" | "out-of-scope" | "deviates" | "noncompliant";

/**
 * An item's status from the checklist and the tests alone: its mark, else whether a test names it;
 * a guarantee with faults is a hole while any of them has no test marked for it.
 */
export const staticStatus = (
	item: Item,
	tests: ReadonlyMap<string, readonly TestRef[]>,
): StaticStatus => {
	const refs = tests.get(item.id) ?? [];
	if (item.mark) return item.mark.kind;
	return refs.length > 0 && unmarkedFaults(item, refs).length === 0 ? "mapped" : "hole";
};

const cell = (s: string) => s.replaceAll("|", "\\|");
const generated =
	"Generated by `pnpm --filter @mod/spec-checklist run report` from the checklist and the tests that name its items. Do not edit.";

/** A summary row's counts: items, then MUST and SHOULD in scope by status, then out of scope. */
function countsOf(
	items: readonly Item[],
	tests: ReadonlyMap<string, readonly TestRef[]>,
): number[] {
	const of = (cls: "MUST" | "SHOULD", st: StaticStatus | "in scope") =>
		items.filter(
			(i) =>
				classOf(i.strength) === cls &&
				(st === "in scope"
					? staticStatus(i, tests) !== "out-of-scope"
					: staticStatus(i, tests) === st),
		).length;
	return [
		items.length,
		of("MUST", "in scope"),
		of("MUST", "mapped"),
		of("MUST", "hole"),
		of("MUST", "noncompliant"),
		of("SHOULD", "in scope"),
		of("SHOULD", "mapped"),
		of("SHOULD", "hole"),
		of("SHOULD", "deviates"),
		items.filter((i) => i.mark?.kind === "out-of-scope").length,
	];
}

/** The summary over every spec: each one's counts by class and status, their total, and the counts by role. */
export function summaryTable(
	specs: readonly Spec[],
	tests: ReadonlyMap<string, readonly TestRef[]>,
): string {
	const counts = specs.map((s) => countsOf(s.items, tests));
	const total = counts.reduce(
		(sum, row) => sum.map((n, k) => n + (row[k] ?? 0)),
		counts[0]?.map(() => 0) ?? [],
	);
	const head =
		"| Items | MUST in scope | MUST mapped | MUST hole | MUST noncompliant | SHOULD in scope | SHOULD mapped | SHOULD hole | SHOULD deviates | Out of scope |";
	return [
		`| Specification ${head}`,
		"|---|---|---|---|---|---|---|---|---|---|---|",
		...specs.map((s, k) => `| [${cell(s.title)}](${s.spec}.md) | ${counts[k]?.join(" | ")} |`),
		`| Total | ${total.join(" | ")} |`,
		"",
		`| Role ${head}`,
		"|---|---|---|---|---|---|---|---|---|---|---|",
		...roles.map(
			(role) =>
				`| ${role} | ${countsOf(
					specs.flatMap((s) => s.items).filter((i) => i.role === role),
					tests,
				).join(" | ")} |`,
		),
		"",
	].join("\n");
}

/**
 * The checklist report: a page of each spec's items, and a README that says how to read them. The
 * summary over every spec is printed, not kept, so a change to one spec touches its page alone.
 */
export function reportFiles(
	specs: readonly Spec[],
	tests: ReadonlyMap<string, readonly TestRef[]>,
	updatedBy: ReadonlyMap<string, readonly string[]>,
): Map<string, string> {
	const files = new Map<string, string>();
	files.set(
		"README.md",
		[
			"# Specification checklist",
			"",
			generated,
			"",
			"Each specification has a page here, `<spec>.md`, with a row for each of its items.",
			"",
			"A status here is read from the checklist and the tests alone: `mapped` (a test names the item), `hole` (no test does), `noncompliant` (a MUST known not met), `deviates` (a SHOULD not followed, by a decision), `out-of-scope` (a feature not offered). Whether a mapped item's tests ran and passed is told by each CI run's compliance report.",
			"",
			"An item's role is the role of the server's it binds: `as` the authorization server, `op` the OpenID Provider, `rs` the resource server at its own protected routes, `rp` the relying party to an upstream IdP, `client` the client sending tokens or assertions out.",
			"",
			"The summary over every specification, by specification and by role, is not kept here: `pnpm --filter @mod/spec-checklist run summary` prints it from the checklist as it stands.",
			"",
		].join("\n"),
	);
	for (const s of specs) {
		const rows = s.items.map((i) => {
			const mark = i.mark;
			const note = [
				...(mark
					? [
							mark.kind === "out-of-scope"
								? mark.reason
								: mark.kind === "deviates"
									? mark.decision
									: mark.issue,
						]
					: []),
				...(i.updates.length > 0 ? [`updates ${i.updates.join(", ")}`] : []),
				...(i.faults ? [`faults: ${i.faults.join(", ")}`] : []),
				...(i.faults && unmarkedFaults(i, tests.get(i.id) ?? []).length > 0
					? [`no test for ${unmarkedFaults(i, tests.get(i.id) ?? []).join(", ")}`]
					: []),
				...((updatedBy.get(i.id)?.length ?? 0) > 0
					? [`updated by ${updatedBy.get(i.id)?.join(", ")}`]
					: []),
			].join("; ");
			const named = (tests.get(i.id) ?? [])
				.map((t) => `${t.pkg} › ${t.file} › ${t.title}`)
				.join("<br>");
			return `| ${i.id} | ${i.strength} | ${i.role} | ${staticStatus(i, tests)} | ${cell(i.text)} | ${cell(named)} | ${cell(note)} |`;
		});
		files.set(
			`${s.spec}.md`,
			[
				`# ${s.title}`,
				"",
				generated,
				"",
				"| Item | Strength | Role | Status | Requirement | Tests | Note |",
				"|---|---|---|---|---|---|---|",
				...rows,
				"",
			].join("\n"),
		);
	}
	return files;
}
