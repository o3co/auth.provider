import type { Item, Spec } from "./checklist.ts";
import { classOf } from "./ids.ts";

/** A test that names an item: its package, its file in the package, and its title. */
export interface TestRef {
	readonly pkg: string;
	readonly file: string;
	readonly title: string;
}

export type StaticStatus = "mapped" | "hole" | "out-of-scope" | "deviates" | "noncompliant";

/** An item's status from the checklist and the tests alone: its mark, else whether a test names it. */
export const staticStatus = (
	item: Item,
	tests: ReadonlyMap<string, readonly TestRef[]>,
): StaticStatus => item.mark?.kind ?? ((tests.get(item.id)?.length ?? 0) > 0 ? "mapped" : "hole");

const cell = (s: string) => s.replaceAll("|", "\\|");
const generated =
	"Generated by `pnpm --filter @mod/spec-checklist run report` from the checklist and the tests that name its items. Do not edit.";

/** The summary over every spec: each one's counts by class and status, and their total. */
export function summaryTable(
	specs: readonly Spec[],
	tests: ReadonlyMap<string, readonly TestRef[]>,
): string {
	const counts = specs.map((s) => {
		const of = (cls: "MUST" | "SHOULD", st: StaticStatus | "in scope") =>
			s.items.filter(
				(i) =>
					classOf(i.strength) === cls &&
					(st === "in scope"
						? staticStatus(i, tests) !== "out-of-scope"
						: staticStatus(i, tests) === st),
			).length;
		return [
			s.items.length,
			of("MUST", "in scope"),
			of("MUST", "mapped"),
			of("MUST", "hole"),
			of("MUST", "noncompliant"),
			of("SHOULD", "in scope"),
			of("SHOULD", "mapped"),
			of("SHOULD", "hole"),
			of("SHOULD", "deviates"),
			s.items.filter((i) => i.mark?.kind === "out-of-scope").length,
		];
	});
	const total = counts.reduce(
		(sum, row) => sum.map((n, k) => n + (row[k] ?? 0)),
		counts[0]?.map(() => 0) ?? [],
	);
	return [
		"| Specification | Items | MUST in scope | MUST mapped | MUST hole | MUST noncompliant | SHOULD in scope | SHOULD mapped | SHOULD hole | SHOULD deviates | Out of scope |",
		"|---|---|---|---|---|---|---|---|---|---|---|",
		...specs.map((s, k) => `| [${cell(s.title)}](${s.spec}.md) | ${counts[k]?.join(" | ")} |`),
		`| Total | ${total.join(" | ")} |`,
		"",
	].join("\n");
}

/**
 * The compliance report: a page of each spec's items, and a README that says how to read them. The
 * summary over every spec is printed, not kept, so a change to one spec touches its page alone.
 */
export function reportFiles(
	specs: readonly Spec[],
	tests: ReadonlyMap<string, readonly TestRef[]>,
	updatedBy: ReadonlyMap<string, readonly string[]>,
): Map<string, string> {
	const files = new Map<string, string>();
	files.set(
		"README.md",
		[
			"# Specification compliance",
			"",
			generated,
			"",
			"Each specification has a page here, `<spec>.md`, with a row for each of its items.",
			"",
			"A status here is read from the checklist and the tests alone: `mapped` (a test names the item), `hole` (no test does), `noncompliant` (a MUST known not met), `deviates` (a SHOULD not followed, by a decision), `out-of-scope` (a feature not offered). Whether a mapped item's tests ran and passed is told by each CI run's compliance report.",
			"",
			"The summary over every specification is not kept here: `pnpm --filter @mod/spec-checklist run summary` prints it from the checklist as it stands.",
			"",
		].join("\n"),
	);
	for (const s of specs) {
		const rows = s.items.map((i) => {
			const mark = i.mark;
			const note = [
				...(mark
					? [
							mark.kind === "out-of-scope"
								? mark.reason
								: mark.kind === "deviates"
									? mark.decision
									: mark.issue,
						]
					: []),
				...(i.updates.length > 0 ? [`updates ${i.updates.join(", ")}`] : []),
				...((updatedBy.get(i.id)?.length ?? 0) > 0
					? [`updated by ${updatedBy.get(i.id)?.join(", ")}`]
					: []),
			].join("; ");
			const named = (tests.get(i.id) ?? [])
				.map((t) => `${t.pkg} › ${t.file} › ${t.title}`)
				.join("<br>");
			return `| ${i.id} | ${i.strength} | ${staticStatus(i, tests)} | ${cell(i.text)} | ${cell(named)} | ${cell(note)} |`;
		});
		files.set(
			`${s.spec}.md`,
			[
				`# ${s.title}`,
				"",
				generated,
				"",
				"| Item | Strength | Status | Requirement | Tests | Note |",
				"|---|---|---|---|---|---|",
				...rows,
				"",
			].join("\n"),
		);
	}
	return files;
}
